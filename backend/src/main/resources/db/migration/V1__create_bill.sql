CREATE TABLE bill (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor                      VARCHAR(200)   NOT NULL,
    patient                     VARCHAR(200),
    invoice_number              VARCHAR(100),
    invoice_date                DATE           NOT NULL,
    due_date                    DATE,
    amount                      DECIMAL(12, 2) NOT NULL,
    description                 VARCHAR(2000),
    paid_on                     DATE,
    insurance_status            VARCHAR(20)    NOT NULL,
    insurance_submitted_on      DATE,
    insurance_decided_on        DATE,
    insurance_reimbursed_amount DECIMAL(12, 2),
    beihilfe_status             VARCHAR(20)    NOT NULL,
    beihilfe_submitted_on       DATE,
    beihilfe_decided_on         DATE,
    beihilfe_reimbursed_amount  DECIMAL(12, 2),
    created_at                  TIMESTAMP WITH TIME ZONE NOT NULL
);
